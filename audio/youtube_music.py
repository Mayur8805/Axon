import os

import yt_dlp
from ytmusicapi import YTMusic

from core.menu import get_input, load_config, save_config

DOWNLOAD_PATH = "./Downloads/Audio"
SETTINGS_KEY = "youtubemusic"
CODEC_OPTIONS = ["flac", "opus", "mp3"]
THUMBNAIL_OPTION = "include thumbnail"
COOKIE_FILE = os.path.join(
    os.path.dirname(os.path.dirname(os.path.abspath(__file__))),
    "youtube_music_cookies.txt",
)
# YouTube Music blocks the default web/ios clients with 403s unless the
# account is verified. The android client is unauthenticated and reliable.
EXTRACTOR_ARGS = {
    "youtubemusic": {"player_client": "android"},
    "web": {"player_client": "android"},
}


def _codec_config(selected_codec):
    return {codec: codec == selected_codec for codec in CODEC_OPTIONS}


def refresh_cookies():
    """Re-export cookies from Firefox into the project cookie file.

    Run this when the 403s start again — the live browser cookies are the
    source of truth, the file is just a cached copy.
    """
    try:
        from yt_dlp.utils import cookies_from_browser
    except ImportError:
        return False

    try:
        cookies = cookies_from_browser("firefox")
        if not cookies:
            return False
        with open(COOKIE_FILE, "w") as fh:
            fh.write(
                "# Netscape HTTP Cookie File\n"
                "# This file is generated by yt-dlp.  Do not edit.\n"
            )
            for c in cookies:
                fh.write(
                    "{}\t{}\t{}\t{}\t{}\t{}\t{}\n".format(
                        c.domain,
                        "TRUE" if c._dict.get("httpOnly") else "FALSE",
                        c.path,
                        "TRUE" if c._dict.get("secure") else "FALSE",
                        int(c.expiration) if c.expiration else 0,
                        c.name,
                        c.value,
                    )
                )
        return True
    except Exception:
        return False


def youtube_music_scraper():
    get_input(
        "Select an option:",
        fetch_fn=scrape_results,
        download_fn=download,
        setting_fn=settings_fn,
    )


def _ytmusic_client():
    """YTMusic client that authenticates from the project cookie file."""
    if os.path.exists(COOKIE_FILE):
        try:
            return YTMusic(COOKIE_FILE)
        except Exception:
            pass
    return YTMusic()


def scrape_results(query):
    ytmusic = _ytmusic_client()
    results = ytmusic.search(query, filter="songs")

    songs = []

    for song in results:
        songs.append({
            "title": song.get("title"),
            "videoId": song.get("videoId"),
            "thumbnail": song["thumbnails"][-1]["url"] if song.get("thumbnails") else None
        })

    return songs


def settings_fn(action, settings=None):
    config = load_config()
    youtube_music_config = config.setdefault(SETTINGS_KEY, {})
    codec_config = youtube_music_config.setdefault(
        "preferredcodec",
        {"flac": True, "opus": False, "mp3": False},
    )
    include_thumbnail = youtube_music_config.setdefault("include_thumbnail", True)

    selected = next((codec for codec in CODEC_OPTIONS if codec_config.get(codec)), "flac")

    if action == "load":
        return {
            "title": "Settings",
            "label": "Download options",
            "type": "toggles",
            "options": [*CODEC_OPTIONS, THUMBNAIL_OPTION],
            "values": {
                **_codec_config(selected),
                THUMBNAIL_OPTION: bool(include_thumbnail),
            },
            "exclusive_groups": [CODEC_OPTIONS],
            "required_groups": [CODEC_OPTIONS],
            "groups": [
                {"title": "Download as", "options": CODEC_OPTIONS},
                {"title": "Cover setting", "options": [THUMBNAIL_OPTION]},
            ],
        }

    if action == "save" and settings:
        values = settings.get("values", {})
        selected = next((codec for codec in CODEC_OPTIONS if values.get(codec)), "flac")
        youtube_music_config["preferredcodec"] = _codec_config(selected)
        youtube_music_config["include_thumbnail"] = bool(values.get(THUMBNAIL_OPTION, True))
        save_config(config)


def _with_thumbnail_postprocessors(postprocessors, include_thumbnail):
    if include_thumbnail:
        postprocessors.extend([
            {"key": "FFmpegThumbnailsConvertor", "format": "jpg"},
            {"key": "EmbedThumbnail"},
        ])

    postprocessors.append({"key": "FFmpegMetadata"})
    return postprocessors


def build_audio_options(codec, progress_hook=None, include_thumbnail=True):
    ydl_opts = {
        "outtmpl": os.path.join(DOWNLOAD_PATH, "%(title)s.%(ext)s"),
        "quiet": False,
        "no_warnings": False,
        "js_runtimes": {"deno": {}},
        "writethumbnail": include_thumbnail,
        "verbose": True,
        # Prefer the cached cookie file; only fall back to reading the live
        # Firefox profile when the file is missing or unusable.
        "extractor_args": EXTRACTOR_ARGS,
    }

    if os.path.exists(COOKIE_FILE):
        ydl_opts["cookiefile"] = COOKIE_FILE
    else:
        ydl_opts["cookiesfrombrowser"] = ("firefox",)

    if codec == "opus":
        ydl_opts.update({
            "format": "bestaudio[ext=webm]/bestaudio/best",
            "postprocessors": _with_thumbnail_postprocessors([
                {
                    "key": "FFmpegExtractAudio",
                    "preferredcodec": "opus",
                },
            ], include_thumbnail),
            "postprocessor_args": {
                "FFmpegExtractAudio": ["-q:a", "0"]
            },
        })
    elif codec == "mp3":
        ydl_opts.update(
            {
                "format": "bestaudio/best",
                "postprocessors": _with_thumbnail_postprocessors([{
                    "key": "FFmpegExtractAudio",
                    "preferredcodec": "mp3",
                    "preferredquality": "0",
                },
                ], include_thumbnail),
                "postprocessor_args": {
                    "FFmpegExtractAudio": [
                        "-q:a", "0",
                        "-compression_level", "0",
                    ]
                },
            }
        )
    else:
        ydl_opts.update(
            {
                "format": "bestaudio/best",
                "postprocessors": _with_thumbnail_postprocessors([{
                    "key": "FFmpegExtractAudio",
                    "preferredcodec": "flac",
                    "preferredquality": "0",
                },
                ], include_thumbnail),
                "postprocessor_args": {
                    "FFmpegExtractAudio": [
                        "-compression_level", "8",
                    ]
                },
            }
        )

    if progress_hook:
        ydl_opts["progress_hooks"] = [progress_hook]

    return ydl_opts


def _strip_thumbnail_postprocessors(postprocessors):
    return [
        pp for pp in postprocessors
        if pp["key"] not in ("EmbedThumbnail", "FFmpegThumbnailsConvertor")
    ]


def _download_with_options(ydl_opts, url):
    with yt_dlp.YoutubeDL(ydl_opts) as ydl:
        ydl.download([url])


def download(item, progress_hook=None, settings=None):
    video_id = item.get("videoId", "")
    url = f"https://music.youtube.com/watch?v={video_id}"
    settings = settings or settings_fn("load")
    values = settings.get("values", {})
    codec = next(
        (codec for codec in CODEC_OPTIONS if values.get(codec)),
        settings.get("selected", "flac"),
    )
    include_thumbnail = bool(values.get(THUMBNAIL_OPTION, True))

    ydl_opts = build_audio_options(
        codec,
        progress_hook=progress_hook,
        include_thumbnail=include_thumbnail,
    )
    try:
        _download_with_options(ydl_opts, url)
        return
    except yt_dlp.utils.DownloadError:
        if not include_thumbnail:
            raise

    # Retry once without thumbnail embedding so the song isn't lost
    ydl_opts_fallback = build_audio_options(codec, progress_hook=progress_hook)
    ydl_opts_fallback["writethumbnail"] = False
    ydl_opts_fallback["postprocessors"] = _strip_thumbnail_postprocessors(
        ydl_opts_fallback["postprocessors"]
    )
    _download_with_options(ydl_opts_fallback, url)